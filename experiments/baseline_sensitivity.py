"""Sensitivity of the classical baselines to the two settings the brief leaves open.

The brief (Section 3b, step 9) fixes the samplers but not two details:

* Stratified sampling: how the budget is spread across the three strata. We ship
  proportional allocation; here we add equal allocation and Neyman (variance-optimal)
  allocation. Neyman is the best any allocation can do, so it bounds every reading.
* Importance sampling: the brief says "half the true annual distribution and half the
  loss-tilted distribution". We sweep the mixing weight on the tilt (0.25 to 0.9).

All variances are exact over the 100^3 term paths (no simulation noise). Output: queries to
1% relative RMSE per scenario and target, and whether any variant would replace the best
classical sampler used for the headline ratios in results/accuracy_per_query.json.

    python experiments/baseline_sensitivity.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from adbq.baselines import PathSpace  # noqa: E402
from adbq.model import SCENARIOS, SHORT, TARGETS  # noqa: E402

EPS = 0.01
MIX = (0.25, 0.5, 0.75, 0.9)
TOL = 0.01   # a variant counts only if it saves more than 1% of the queries


def strat_queries(ps, key, eps):
    """Queries to relative RMSE eps for proportional, equal and Neyman allocation."""
    laws, w = ps.strata()
    mu = ps.mu(key)
    v = []
    for l1, l2, l3 in laws:
        P = np.einsum("i,j,k->ijk", l1, l2, l3)
        m = (P * ps.f[key]).sum()
        v.append(max((P * ps.f[key] ** 2).sum() - m**2, 0.0))
    w, v = np.array(w), np.array(v)
    den = (eps * mu) ** 2
    out = {}
    for name, a in (("proportional", w / w.sum()), ("equal", np.full(3, 1 / 3))):
        out[name] = float((w**2 * v / a).sum() / den)
    out["neyman"] = float((w * np.sqrt(v)).sum() ** 2 / den)
    return out


def is_queries(ps, key, mix, eps):
    tilt = ps.p * ps.ann_loss
    q = (1 - mix) * ps.p + mix * tilt / tilt.sum()
    P = np.einsum("i,j,k->ijk", ps.p, ps.p, ps.p)
    Q = np.einsum("i,j,k->ijk", q, q, q)
    wt = np.divide(P, Q, out=np.zeros_like(P), where=Q > 0)
    mu = (P * ps.f[key]).sum()
    var = (Q * (ps.f[key] * wt) ** 2).sum() - mu**2
    return float(var / (eps * mu) ** 2)


def main():
    acc = json.loads((ROOT / "results" / "accuracy_per_query.json").read_text())["scenarios"]
    out, flips = {}, []
    for name in SCENARIOS:
        ps = PathSpace(SCENARIOS[name])
        out[name] = {}
        for key, short in zip(TARGETS, SHORT):
            need = acc[name][key]["queries_needed"][str(EPS)]
            st = strat_queries(ps, key, EPS)
            iq = {f"{m:g}": is_queries(ps, key, m, EPS) for m in MIX}
            # shipped settings, exact on both sides (MC and Sobol from the headline run)
            shipped = {"mc": need["mc"][0], "sobol": need["sobol"][0], "strat": st["proportional"], "is": iq["0.5"]}
            best_m = min(shipped, key=shipped.get)
            variant_best = min(min(st.values()), min(iq.values()))
            q = need["qae"][0]
            row = {"shipped_best": [best_m, shipped[best_m]], "strat": st, "is_mix": iq, "qae": q,
                   "ratio_shipped": shipped[best_m] / q,
                   "ratio_with_variants": min(shipped[best_m], variant_best) / q}
            if variant_best < (1 - TOL) * shipped[best_m]:
                flips.append((name, short))
            out[name][short] = row
    res = {"eps_rel": EPS, "is_mix": MIX, "rows": out, "best_classical_changed": flips}
    (ROOT / "results" / "baseline_sensitivity.json").write_text(json.dumps(res, indent=1))

    L = ["# Baseline sensitivity: open settings in the brief", "",
         "Generated by `experiments/baseline_sensitivity.py`. Queries to 1% relative RMSE, exact variances. "
         "Ratio = best classical / IQAE queries (above 1 favours IQAE).", "",
         "| scenario | target | shipped best classical | strat prop. | strat equal | strat Neyman | "
         "IS mix " + " | IS mix ".join(f"{m:g}" for m in MIX) + " | IQAE | ratio (shipped) | ratio (all variants) |",
         "|---|---|---|" + "---:|" * (6 + len(MIX))]
    f = lambda x: f"{x:.3g}"
    for name, rows in out.items():
        for short, r in rows.items():
            L.append(f"| {name} | {short} | {r['shipped_best'][0]} {f(r['shipped_best'][1])} | "
                     + " | ".join(f(r["strat"][k]) for k in ("proportional", "equal", "neyman")) + " | "
                     + " | ".join(f(r["is_mix"][f'{m:g}']) for m in MIX)
                     + f" | {f(r['qae'])} | {r['ratio_shipped']:.2f} | {r['ratio_with_variants']:.2f} |")
    L += ["", ("No variant beats the shipped best classical sampler by more than 1% on any target: the open settings do not "
               "change the headline ratios." if not flips else
               "Targets where a variant beats the shipped best classical sampler: "
               + ", ".join(f"{a} / {b}" for a, b in flips) + ". Use the 'all variants' ratio for these."),
          "", "Neyman allocation is variance-optimal, so it bounds every possible stratified allocation. "
          "Mix 0.5 is the brief's proposal."]
    (ROOT / "results" / "baseline_sensitivity.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[-4:]))


if __name__ == "__main__":
    main()
