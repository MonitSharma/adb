"""Result files for the five ADB scenarios in the benchmark's submission format.

Writes results/benchmark_submission/<scenario>.json (README "Submit your results" format of
joint-loss-baseline v0.5.0) by running team_solver.py once per scenario, plus summary.md
with each estimate against the exact reference and the evaluator's tolerance.

    python experiments/benchmark_submission.py
"""
import json
import secrets
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from adbq.benchmark import case_from_config, check_result, exact_targets, tolerance  # noqa: E402
from adbq.model import SCENARIOS, SHORT, TARGETS  # noqa: E402

OUT = ROOT / "results" / "benchmark_submission"
SEED = 20261116


def run(name: str) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        (work / "cases").mkdir()
        (work / "data").mkdir()
        shutil.copyfile(ROOT / "benchmark_inputs/data/adb_terms.json", work / "data/adb_terms.json")
        shutil.copyfile(ROOT / f"benchmark_inputs/scenarios/{name}.json", work / "cases/case.json")
        case = case_from_config(work / "cases/case.json")
        request = {"schema_version": 1, "run_id": secrets.token_hex(16), "problem_id": case.problem_id,
                   "track": "adb_drb", "config_file": "cases/case.json", "seed": SEED,
                   "samples": 8192, "targets": list(TARGETS)}
        (work / "request.json").write_text(json.dumps(request))
        subprocess.run([sys.executable, str(ROOT / "team_solver.py"), "--request", "request.json",
                        "--output", "result.json"], cwd=work, check=True)
        sub = json.loads((work / "result.json").read_text())
        check_result(sub, case, request)
        return sub, case


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    L = ["# Benchmark-format results (ADB track)", "",
         "Generated by `experiments/benchmark_submission.py` through `team_solver.py`; one file per "
         "scenario in the joint-loss-baseline submission format. Execution `quantum_simulator`: IQAE on "
         "the emulated state preparation. Error is relative to the exact reference; the evaluator "
         "passes a target when RMSE over repeats is at most its tolerance.", "",
         "| scenario | target | estimate | exact | rel. error | tolerance (rel.) |", "|---|---|---:|---:|---:|---:|"]
    for name in SCENARIOS:
        sub, case = run(name)
        sub.pop("run_id", None)
        (OUT / f"{name}.json").write_text(json.dumps(sub, indent=2) + "\n")
        ref = exact_targets(case)
        for k, s in zip(TARGETS, SHORT):
            e = sub["estimates"][k]
            L.append(f"| {name} | {s} | {e:.6g} | {ref[k]:.6g} | {abs(e - ref[k]) / ref[k]:.2%} | "
                     f"{tolerance(case, k, ref[k]) / ref[k]:.0%} |")
        print(name, "ok", sub["resources"])
    (OUT / "summary.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
