"""Certified intervals: coverage of IQAE confidence intervals, Clopper-Pearson versus
Chernoff-Hoeffding, on the five base-scenario targets of the brief.

For every target and target half-width, IQAE is emulated shot by shot at the exact amplitude
of the verified oracle (2,000 runs per cell). We record the empirical coverage of the reported
interval (nominal 99%), the mean number of queries, the relative RMSE of the point estimate and
the interval half-width. Writes results/coverage.json and results/coverage.md.

Run: python experiments/coverage.py
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from adbq.circuits import apply, prob_good          # noqa: E402
from adbq.model import SCENARIOS, SHORT, TARGETS    # noqa: E402
from adbq.oracle import build_oracle                # noqa: E402
from adbq.qae import iqae                           # noqa: E402

ALPHA = 0.01
EPS_REL = (0.1, 0.03, 0.01)
RUNS = 2000
SEED = 20261113


def wilson_lower(k: int, n: int, z: float = 2.576) -> float:
    """Lower 99% Wilson bound on a coverage proportion (to show the coverage is not luck)."""
    p = k / n
    d = 1 + z * z / n
    return float((p + z * z / (2 * n) - z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n))) / d)


def main():
    rng = np.random.default_rng(SEED)
    s = SCENARIOS["adb-base"]
    out = {"alpha": ALPHA, "runs": RUNS, "targets": {}}
    for key, short in zip(TARGETS, SHORT):
        o = build_oracle(s, key)
        a = prob_good(apply({0: 1.0}, o.A), o.good)
        cell = {"amplitude": a, "f_max": o.f_max, "methods": {}}
        for method in ("cp", "ch"):
            rows = []
            for eps in EPS_REL:
                t0 = time.time()
                runs = [iqae(a, eps * a, rng, alpha=ALPHA, method=method) for _ in range(RUNS)]
                est = np.array([x[0] for x in runs])
                cov = sum(x[2][0] <= a <= x[2][1] for x in runs)
                rows.append({
                    "eps_rel": eps,
                    "coverage": cov / RUNS,
                    "coverage_lower99": wilson_lower(cov, RUNS),
                    "queries": float(np.mean([x[1] for x in runs])),
                    "rel_rmse": float(np.sqrt(np.mean((est - a) ** 2)) / a),
                    "half_width_rel": float(np.mean([(x[2][1] - x[2][0]) / 2 for x in runs]) / a),
                    # a miss is narrow and confidently wrong: record how wrong (relative error of the estimate)
                    "misses": int(RUNS - cov),
                    "worst_miss_rel_err": float(max((x[0] / a - 1 for x in runs if not x[2][0] <= a <= x[2][1]),
                                                    key=abs, default=0.0)),
                    "max_abs_rel_err": float(np.max(np.abs(est / a - 1))),
                    "seconds": time.time() - t0,
                })
            cell["methods"][method] = rows
        out["targets"][short] = cell
        print(short, {m: [f"{r['coverage']:.4f}/{r['queries']:.3g}" for r in v] for m, v in cell["methods"].items()},
              flush=True)
    # query saving of CP over CH at equal realised RMSE (constant c in queries = c sqrt((1-a)/a) / rmse)
    ratios = []
    for cell in out["targets"].values():
        a = cell["amplitude"]
        f = np.sqrt((1 - a) / a)
        c = {m: np.median([r["queries"] * r["rel_rmse"] / f for r in rows]) for m, rows in cell["methods"].items()}
        cell["iqae_constant"] = c
        ratios.append(c["ch"] / c["cp"])
    out["cp_saving_over_ch"] = {"min": float(min(ratios)), "max": float(max(ratios)), "median": float(np.median(ratios))}
    allcov = [r["coverage"] for cell in out["targets"].values() for rows in cell["methods"].values() for r in rows]
    out["min_coverage"] = float(min(allcov))
    (ROOT / "results" / "coverage.json").write_text(json.dumps(out, indent=1))

    L = ["# Certified intervals: coverage of IQAE", "",
         f"Generated by `experiments/coverage.py`. Base scenario, nominal confidence {1 - ALPHA:.0%}, "
         f"{RUNS:,} emulated runs per cell. CP = Clopper-Pearson bounds per round; CH = Chernoff-Hoeffding.", "",
         "| target | method | target half-width | coverage | 99% lower bound on coverage | mean queries | relative RMSE | misses | worst miss |",
         "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for short, cell in out["targets"].items():
        for m, rows in cell["methods"].items():
            for r in rows:
                L.append(f"| {short} | {m.upper()} | {r['eps_rel']:.0%} | {r['coverage']:.4f} | {r['coverage_lower99']:.4f} | "
                         f"{r['queries']:,.0f} | {r['rel_rmse']:.2%} | {r['misses']} | {r['worst_miss_rel_err']:+.0%} |")
    s_ = out["cp_saving_over_ch"]
    L += ["", f"Lowest coverage in any cell: {out['min_coverage']:.4f}. At equal realised error, Clopper-Pearson "
          f"needs {s_['median']:.2f}x fewer queries than Chernoff-Hoeffding (range {s_['min']:.2f}x-{s_['max']:.2f}x).",
          "", "A miss is narrow and confidently wrong; 'worst miss' is the relative error of the estimate in the "
          "worst run whose interval excluded the exact value."]
    (ROOT / "results" / "coverage.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
