"""Exact ground truth for the grid Boltzmann model (src/adbq/grid.py).

* Calibration and exact VaR / CVaR for grids 2x2 ... 10x10, scenarios independent / base /
  common-shock (kappa = 1) and the contagion knob kappa in {2, 3, 3.5, 4} (base marginals).
* Cross-check of the two exact engines (enumeration vs transfer matrix) for n <= 20.
* Exactness frontier: transfer-matrix wall-clock for square grids up to TM_MAX_ROWS
  (loss law included). Wider grids have no exact engine here: there, any number is an
  estimate and is labelled as one.

Writes results/grid_exact.json and results/grid_summary.md.
Run: python experiments/grid_exact.py [--frontier-max 12]
"""
import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from adbq.grid import (ENUM_MAX_BITS, TM_MAX_ROWS, TransferMatrix, brief_trigger_law,  # noqa: E402
                       calibrated_grid, calibration_residual, enumerate_law, exact_loss_pmf)
from adbq.risk import ALPHAS, _tag, risk_summary                                       # noqa: E402

SHAPES = [(2, 2), (3, 3), (4, 4), (4, 5), (5, 5), (6, 6), (8, 8), (10, 10)]
SCEN = ("adb-independent", "adb-base", "adb-common-shock")
KAPPAS = (2.0, 3.0, 3.5, 4.0)
KEYS = ["E[L]"] + [f"{m}{_tag(a)}" for a in ALPHAS for m in ("VaR", "CVaR")]


def one(rows, cols, scen, kappa):
    t0 = time.time()
    m = calibrated_grid(rows, cols, scen, kappa=kappa)
    t_fit = time.time() - t0
    t0 = time.time()
    v, p = exact_loss_pmf(m)
    t_loss = time.time() - t0
    r = risk_summary(v, p)
    top = float(p[v >= 0.6 * v.max()].sum())            # mass of the 'nearly everything' mode
    out = {"rows": rows, "cols": cols, "n": m.n, "scenario": scen, "kappa": kappa,
           "fit_seconds": t_fit, "loss_seconds": t_loss, "calibration_residual": calibration_residual(m),
           "J_range": [float(m.J.min()), float(m.J.max())] if len(m.J) else [0.0, 0.0],
           "theta_range": [float(m.theta.min()), float(m.theta.max())],
           "max_loss": float(v.max()), "p_loss_ge_60pct_max": top, **r}
    if m.n <= min(20, ENUM_MAX_BITS):
        d = enumerate_law(m)
        pe = np.bincount(d["loss_units"], weights=d["pi"], minlength=len(p))
        out["enum_vs_tm_max_abs"] = float(np.abs(pe - p).max())
    return out


def frontier(max_rows):
    rows = []
    for R in range(4, max_rows + 1, 2):
        m = calibrated_grid(R, R, "adb-independent")      # no fitting cost; same contraction cost
        t0 = time.time()
        TransferMatrix(m).loss_pmf()
        rows.append({"rows": R, "n": R * R, "seconds": time.time() - t0})
        print(f"  frontier {R}x{R}: {rows[-1]['seconds']:.1f}s", flush=True)
    return rows


def render(d):
    L = ["# Grid Boltzmann model: exact results", "",
         "Generated by `experiments/grid_exact.py`. USD m. Calibration targets from the brief: "
         f"P(trigger) KGZ {d['targets']['p'][0]:.5f}, TJK {d['targets']['p'][1]:.5f}; "
         f"P(both) base {d['targets']['p_both']['adb-base']:.5f}, common-shock "
         f"{d['targets']['p_both']['adb-common-shock']:.5f}.", "",
         "| grid | n | scenario | kappa | " + " | ".join(KEYS) + " | P(L >= 0.6 max) | calib. resid. | enum vs TM |",
         "|---|---:|---|---:|" + "---:|" * (len(KEYS) + 3)]
    for r in d["runs"]:
        L.append(f"| {r['rows']}x{r['cols']} | {r['n']} | {r['scenario'].replace('adb-', '')} | {r['kappa']:g} | "
                 + " | ".join(f"{r[k] / 1e6:.1f}" for k in KEYS)
                 + f" | {r['p_loss_ge_60pct_max']:.1e} | {r['calibration_residual']:.0e} | "
                 + (f"{r['enum_vs_tm_max_abs']:.0e}" if "enum_vs_tm_max_abs" in r else "-") + " |")
    L += ["", "## Exactness frontier (transfer matrix, loss law included)", "",
          "| grid | bits | seconds |", "|---|---:|---:|"]
    for f in d["frontier"]:
        L.append(f"| {f['rows']}x{f['rows']} | {f['n']} | {f['seconds']:.2f} |")
    fr = [f for f in d["frontier"] if f["seconds"] > 0.05]
    if len(fr) >= 2:
        R = np.array([f["rows"] for f in fr]); t = np.log([f["seconds"] for f in fr])
        slope, icpt = np.polyfit(R, t, 1)
        L += ["", f"Fitted growth: x{np.exp(2 * slope):.0f} per two extra rows. Extrapolated "
              "single contraction: " + ", ".join(
                  f"{r}x{r} ~ {np.exp(icpt + slope * r):.2g} s" for r in (14, 16, 20, 24)) + "."]
    L += ["", f"`TM_MAX_ROWS = {d['tm_max_rows']}` is a runtime cap, not a hard wall: the "
          "extrapolation above says where exact contraction stops being practical. Beyond it "
          "(and beyond " f"{d['enum_max_bits']} bits for enumeration) every number is an "
          "estimate and is labelled as one. Exact enumeration is the independent check up to 20 bits.",
          "", "Rows with kappa >= 3.5 put several percent of the mass on a near-total common "
          "mode (column P(L >= 0.6 max)): a deliberate multimodal stress world for MCMC, not a "
          "realistic portfolio calibration."]
    return "\n".join(L) + "\n"


def main(frontier_max):
    law = {s: brief_trigger_law(s) for s in SCEN}
    out = {"targets": {"p": law["adb-base"]["p"], "payout": law["adb-base"]["payout"],
                       "p_both": {s: law[s]["p_both"] for s in SCEN}},
           "tm_max_rows": TM_MAX_ROWS, "enum_max_bits": ENUM_MAX_BITS, "runs": []}
    for R, C in SHAPES:
        for s in SCEN:
            out["runs"].append(one(R, C, s, 1.0))
        for k in KAPPAS:
            out["runs"].append(one(R, C, "adb-base", k))
        print(f"{R}x{C} done", flush=True)
    out["frontier"] = frontier(frontier_max)
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--frontier-max", type=int, default=TM_MAX_ROWS)
    a = ap.parse_args()
    d = main(a.frontier_max)
    (ROOT / "results" / "grid_exact.json").write_text(json.dumps(d, indent=1))
    (ROOT / "results" / "grid_summary.md").write_text(render(d), encoding="utf-8")
    print(render(d))
