"""Exact QeMCMC scorecard on a 3 x 4 grid (12 bits), as Notebook 23 of the logistics project.

For each world (kappa = 1 calibrated; kappa = 4 high contagion) and each sampler, the
number of MH steps needed for 10% relative RMSE on CVaR95 (under the true law, estimated
on the loss-tilted law with exact importance correction) is computed *exactly* from the
transition matrix: sigma^2_asym(w psi) / (0.1 CVaR)^2. Each sampler keeps its best tilt on
the grid LAMBDAS. Spectral gaps are reported at that tilt.

Why 3 x 4 and not 4 x 4: the quantum proposal matrix is dense; at 16 bits it has 2^32
entries, so exact matrices stop at 12 bits. The 4 x 4 worlds are benchmarked with sampled
chains in experiments/qmcmc_chains.py.

Writes results/qmcmc_exact.json. Run: python experiments/qmcmc_exact.py
"""
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from adbq.grid import calibrated_grid                                     # noqa: E402
from adbq.qmcmc import (Target, logistics, proposal_matrices, spectral,  # noqa: E402
                        steps_to_accuracy)

SHAPE = (3, 4)
WORLDS = {"calibrated (kappa = 1)": 1.0, "high contagion (kappa = 4)": 4.0}
LAMBDAS = (0.0, 0.5, 1.0, 1.5, 2.0, 2.5, 3.0)
SEED = 20261114
CLASSICAL = ("Local MH", "Local + random jump", "Local + pair flips", "Local + plaquette flips")
QUANTUM = ("Local + quantum (default)", "Local + quantum (short time)", "Pair flips + quantum (short)")
CONTROLS = ("Local + mismatched quantum",)


def contestants(Q):
    h = 0.5
    return {
        "Local MH": Q["local"],
        "Local + random jump": h * Q["local"] + h * Q["uniform"],
        "Local + pair flips": h * Q["local"] + h * Q["pair"],
        "Local + plaquette flips": h * Q["local"] + h * Q["plaquette"],
        "Local + quantum (default)": h * Q["local"] + h * Q["quantum_default"],
        "Local + quantum (short time)": h * Q["local"] + h * Q["quantum_short"],
        "Pair flips + quantum (short)": h * Q["pair"] + h * Q["quantum_short"],
        "Local + mismatched quantum": h * Q["local"] + h * Q["quantum_mismatch"],
    }


def main():
    out = {"shape": SHAPE, "lambdas": LAMBDAS, "seed": SEED, "worlds": {}}
    for world, kappa in WORLDS.items():
        m = calibrated_grid(*SHAPE, kappa=kappa)
        steps = {}
        for lam in LAMBDAS:
            t0 = time.time()
            tgt = Target(m, lam)
            rng = np.random.default_rng(SEED)            # same quantum draws at every tilt
            Q = proposal_matrices(m, tgt, rng)
            for name, M in contestants(Q).items():
                steps.setdefault(name, {})[lam] = steps_to_accuracy(M, tgt)
            steps.setdefault("i.i.d. from tilted law", {})[lam] = tgt.iid_variance() / (0.1 * tgt.cvar) ** 2
            print(f"{world} lam={lam}: {time.time() - t0:.0f}s", flush=True)
        best = {k: min(v, key=v.get) for k, v in steps.items()}
        gaps = {}
        for lam in sorted(set(best.values())):
            tgt = Target(m, lam)
            Q = contestants(proposal_matrices(m, tgt, np.random.default_rng(SEED)))
            for name in Q:
                if best[name] == lam:
                    gaps[name] = spectral(Q[name], tgt)
        tgt0 = Target(m, 0.0)
        bc = min(CLASSICAL, key=lambda k: steps[k][best[k]])
        bq = min(QUANTUM, key=lambda k: steps[k][best[k]])
        out["worlds"][world] = {
            "kappa": kappa, "VaR95": tgt0.var, "CVaR95": tgt0.cvar,
            "steps": {k: {str(l): v for l, v in d.items()} for k, d in steps.items()},
            "best_lambda": best, "best_steps": {k: steps[k][best[k]] for k in steps},
            "spectral_at_best": gaps,
            "best_classical": bc, "best_quantum": bq,
            "quantum_speedup_over_best_classical": steps[bc][best[bc]] / steps[bq][best[bq]],
        }
    return out


def render(d):
    L = ["# QeMCMC exact scorecard (3 x 4 grid, 12 bits)", "",
         "Generated by `experiments/qmcmc_exact.py`. Steps = MH steps (one loss evaluation each) for "
         "10% relative RMSE on CVaR95, computed exactly from the transition matrix; every sampler "
         "uses its best tilt lambda (per USD 100m).", ""]
    for w, r in d["worlds"].items():
        L += [f"## {w}: CVaR95 = USD {r['CVaR95'] / 1e6:.1f}m", "",
              "| sampler | best lambda | steps for 10% | spectral gap | relaxation time |",
              "|---|---:|---:|---:|---:|"]
        for k, s in sorted(r["best_steps"].items(), key=lambda kv: kv[1]):
            g = r["spectral_at_best"].get(k)
            L.append(f"| {k} | {r['best_lambda'][k]:g} | {s:,.0f} | "
                     + (f"{g['gap']:.2e} | {g['relaxation_time']:,.0f} |" if g else "- | - |"))
        L += ["", f"Best classical: {r['best_classical']}; best quantum: {r['best_quantum']}; "
              f"quantum speed-up over best classical: **{r['quantum_speedup_over_best_classical']:.2f}x** "
              "(below 1 = classical wins).", ""]
    return "\n".join(L)


if __name__ == "__main__":
    d = main()
    (ROOT / "results" / "qmcmc_exact.json").write_text(json.dumps(d, indent=1))
    (ROOT / "results" / "qmcmc_exact.md").write_text(render(d), encoding="utf-8")
    print(render(d))
